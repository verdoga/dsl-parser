// Package reporter печатает результат обработки каждого TXT и накапливает
// статистику запуска. Фактическое действие и причину сбоя он получает из
// storage.Report. model.Result задаёт строки, фатальные диагностики и единый
// счётчик нефатальных ошибок для пофайлового вывода и итогов.
// Пакет не разбирает DSL и не записывает JSON.
//
// Форматы одной строки для успешно сохранённого файла:
// УСПЕХ: СОЗДАН | путь: "<абсолютный путь>" | строк: <N или нет данных> | ошибок разбора: <N>
// УСПЕХ: ЗАМЕНЁН | путь: "<абсолютный путь>" | строк: <N или нет данных> | ошибок разбора: <N>
//
// Формат одной строки для неудачной записи:
// ОШИБКА: <ДЕЙСТВИЕ> | путь: "<абсолютный путь>" | строк: <N или нет данных> | ошибок разбора: <N> | причина: <текст ошибки>
// ДЕЙСТВИЕ берётся из storage.Report.Action: not-written — НЕ СОЗДАН,
// created — СОЗДАН, replaced — ЗАМЕНЁН. При nil в Err причиной служит
// фатальная диагностика, а при её отсутствии — «причина не указана».
// CR и LF выводятся как видимые \r и \n.
// Фатальная диагностика последнего Processing означает «ОШИБКА» и добавляет
// « | фатальная ошибка: <код>». Число строк при раннем отказе
// IO001/P001/P002/P013/P014 — «нет данных».
// Неизвестное число строк выводится как «нет данных» и при успешной записи.
// При пустом SourcePath выводится «путь: неизвестен»; известный путь
// заключается в кавычки с экранированием по правилам Go для %q.
//
// Формат единственной итоговой строки после всех Record:
// ИТОГО | всего: <N> | сохранено: <N> | сбоев: <N> | файлов с ошибками разбора: <N> | ошибок разбора: <N>
// Сбоем считается отказ обработки или записи, включая фатальные диагностики;
// один файл увеличивает этот счётчик не более чем на один. В ошибки разбора
// входят только нефатальные диагностики уровня error текущего Processing,
// кроме IO001. Счётчики независимы: сохранение может сопровождаться ошибкой
// очистки, а нефатальные ошибки разбора — отказом записи. Если Record не
// вызывался, все числа равны нулю. Предупреждения и рекомендации в итог не входят.
// При ошибке поиска добавляется « | обход: неполный» и код завершения равен 1;
// неизвестное число недоступных файлов не включается в счётчики файлов.
package reporter

import (
	"fmt"

	"github.com/verdoga/dsl-parser/model"
	"github.com/verdoga/dsl-parser/storage"
)

// Reporter хранит счётчики одного последовательного запуска и печатает
// результаты в стандартную консоль; экземпляр принадлежит вызывающему коду.
type Reporter struct {
	// total — число полученных отчётов storage.
	total int
	// saved — число фактически созданных или заменённых JSON, включая сбой очистки.
	saved int
	// failed — число файлов с отказом обработки или записи, включая фатальные диагностики.
	failed int
	// filesWithParseErrors — число файлов с хотя бы одной нефатальной ошибкой разбора.
	filesWithParseErrors int
	// parseErrors — суммарное число нефатальных ошибок текущего разбора без IO001.
	parseErrors int
	// incompleteDiscovery — поиск завершился ошибкой; total содержит только найденные файлы.
	incompleteDiscovery bool
}

// New создаёт Reporter с нулевыми счётчиками и выводом в стандартную консоль.
func New() *Reporter {
	return &Reporter{}
}

// Record принимает модель одного TXT и отчёт его записи, извлекает сводку,
// обновляет счётчики и печатает ровно одну строку в формате пакета.
// Фатальная диагностика, report.Err != nil или action=not-written означает
// «ОШИБКА». Фактически сохранённый JSON учитывается даже при ошибке очистки.
// Вызывается один раз после storage.Save для каждого переданного на обработку
// TXT. Дополнительную ошибку отдельным аргументом не принимает.
func (r *Reporter) Record(result model.Result, report storage.Report) {
	summary := summarizeFile(result, report)
	r.total++
	if isFailure(summary) {
		r.failed++
	}
	if summary.action == storage.ActionCreated || summary.action == storage.ActionReplaced {
		r.saved++
	}
	if summary.parseErrors > 0 {
		r.filesWithParseErrors++
	}
	r.parseErrors += summary.parseErrors
	fmt.Println(formatFileLine(summary))
}

// MarkIncompleteDiscovery отмечает ошибку поиска без выдуманного числа
// недоступных файлов. Причину печатает вызывающий код; повторный вызов допустим.
func (r *Reporter) MarkIncompleteDiscovery() {
	r.incompleteDiscovery = true
}

// Finish печатает одну итоговую строку и возвращает 0 при failed=0 и полном
// обходе, иначе 1. Вызывается один раз после всех Record. Код 2 при ошибке
// параметров запуска выбирает вызывающий код до обработки файлов.
func (r *Reporter) Finish() int {
	line := formatTotalLine(r.total, r.saved, r.failed, r.filesWithParseErrors, r.parseErrors)
	if r.incompleteDiscovery {
		line += " | обход: неполный"
	}
	fmt.Println(line)
	if r.failed != 0 || r.incompleteDiscovery {
		return 1
	}
	return 0
}
