// Package console разбирает параметры запуска dslparser, проверяет исходный путь
// и печатает русскоязычную справку и сообщения об ошибках параметров.
// Результат пакета — параметры для дальнейшей обработки и решение, запускать ли её.
package console

// Params — проверенные параметры одного запуска; поля доступны пакету app.
type Params struct {
	// Path — абсолютный очищенный путь к обычному TXT-файлу или каталогу.
	Path string

	// Depth — максимальное число уровней подкаталогов; nil означает отсутствие ограничения.
	// Значение 0 ограничивает поиск переданным каталогом; для пути к файлу поле игнорируется.
	Depth *int

	// Replace — разрешение повторного разбора и замены целевого JSON.
	Replace bool
}
