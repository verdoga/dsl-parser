// Package diagnostics хранит неизменяемые описания диагностик парсера DSL,
// предоставляет поиск по коду и безопасный доступ к необязательной функции проверки.
// Пакет не разбирает DSL и не создаёт экземпляры диагностик в JSON-результате.
package diagnostics

// Code — устойчивый машинный код диагностики.
type Code string

const (
	P001  Code = "P001"  // Некорректная кодировка UTF-8.
	P002  Code = "P002"  // Неподдерживаемый перевод строки.
	P003  Code = "P003"  // Неизвестная DSL-конструкция.
	P004  Code = "P004"  // Нарушен обязательный разделитель объявления.
	P005  Code = "P005"  // Использована неподдерживаемая форма тега.
	P006  Code = "P006"  // Отсутствует обязательный структурный параметр.
	P007  Code = "P007"  // Лишние параметры или запрещённое содержимое объявления.
	P008  Code = "P008"  // Неправильное открытие блока.
	P009  Code = "P009"  // Закрытие несуществующего блока.
	P010  Code = "P010"  // Неправильная строка закрытия блока.
	P011  Code = "P011"  // Незакрытый блок.
	P012  Code = "P012"  // Неэкранированная фигурная скобка в текстовом значении.
	P013  Code = "P013"  // Не удалось получить объявление версии.
	P014  Code = "P014"  // Версия DSL не поддерживается.
	P015  Code = "P015"  // Незавершённый разбор строки.
	IO001 Code = "IO001" // Техническая ошибка чтения входного файла.
)

// Severity — уровень серьёзности диагностики по JSON-контракту.
type Severity string

const (
	SeverityError          Severity = "error"          // Ошибка.
	SeverityWarning        Severity = "warning"        // Предупреждение.
	SeverityRecommendation Severity = "recommendation" // Рекомендация.
)

// Scope — область диагностики в JSON-контракте.
type Scope string

const (
	ScopeElement  Scope = "element"  // Диагностика элемента строки.
	ScopeLine     Scope = "line"     // Диагностика строки.
	ScopeBlock    Scope = "block"    // Диагностика блочной конструкции.
	ScopeDocument Scope = "document" // Диагностика документа.
)
